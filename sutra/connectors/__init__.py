"""Connector abstraction and contract layer for SAMANVAYA · SŪTRA.

Provides a unified, provider-neutral contract for integrating external tools,
services, and environments via MCP (Model Context Protocol), REST, and CLI.

Design Invariants:
- Zero coupling to Telegram or UI layers.
- Strict authorization boundary via PermissionEngine.
- Reuses centralized resilience (retry, rate limit, circuit breakers).
- Correlates with ActivityStore via request_id.
- Never stores plaintext credentials or secrets in connector metadata.
"""
